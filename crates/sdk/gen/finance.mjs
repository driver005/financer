#!/usr/bin/env node
// Writes crates/sdk/src/finance.rs from the finance API's OpenAPI document (apps/mobile/openapi.json,
// itself written by the server: `make gen-api`). One Rust record or enum per schema and one typed
// async call per operation, so the SDK cannot drift from the server.
//
//   node crates/sdk/gen/finance.mjs          write the file
//   node crates/sdk/gen/finance.mjs --check  fail if the file is not what the document produces (CI)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const doc = JSON.parse(readFileSync(join(root, "apps/mobile/openapi.json"), "utf8"));
const out = join(root, "crates/sdk/src/finance.rs");
const schemas = doc.components.schemas;

const fail = (m) => {
  throw new Error(`finance.mjs: ${m}`);
};
const refName = (r) => r.split("/").pop();
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const pascal = (s) => s.split(/[_\-\s]+/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const doc3 = (text, indent) => (text ? text.split("\n").map((l) => `${indent}/// ${l}`.trimEnd()).join("\n") + "\n" : "");

/** The Rust type of a schema, and whether it is optional (a null in it). */
function rust(s) {
  if (s.$ref) return { t: refName(s.$ref), opt: false };
  if (s.oneOf) {
    const rest = s.oneOf.filter((x) => x.type !== "null");
    if (rest.length !== 1) fail(`oneOf with ${rest.length} choices: ${JSON.stringify(s).slice(0, 120)}`);
    return { t: rust(rest[0]).t, opt: s.oneOf.some((x) => x.type === "null") || rust(rest[0]).opt };
  }
  if (s.type === undefined) return { t: "JsonValue", opt: true }; // "any value"
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const opt = types.includes("null");
  const type = types.find((t) => t !== "null");
  switch (type) {
    case "string":
      return { t: "String", opt };
    case "boolean":
      return { t: "bool", opt };
    case "number":
      return { t: "f64", opt };
    case "integer":
      return { t: s.format === "int64" ? "i64" : s.format === "int32" ? "i32" : s.minimum === 0 ? "u32" : "i64", opt };
    case "array": {
      const item = rust(s.items);
      return { t: `Vec<${item.opt ? `Option<${item.t}>` : item.t}>`, opt };
    }
    case "object":
      if (s.additionalProperties !== undefined) {
        const v = s.additionalProperties && Object.keys(s.additionalProperties).length ? rust(s.additionalProperties) : { t: "JsonValue", opt: false };
        return { t: `HashMap<String, ${v.t}>`, opt };
      }
      return { t: "JsonValue", opt };
    default:
      return fail(`type ${JSON.stringify(s.type)} in ${JSON.stringify(s).slice(0, 120)}`);
  }
}

const lines = [];
const p = (s = "") => lines.push(s);

p("// @generated by crates/sdk/gen/finance.mjs from apps/mobile/openapi.json. Do not edit: change the");
p("// server's annotations, run `make gen-api`, then `node crates/sdk/gen/finance.mjs`.");
p("//");
p("//! The finance API as typed calls: one record or enum per schema, one async call per operation.");
p("");
p("use std::collections::HashMap;");
p("use std::sync::Arc;");
p("");
p("use serde::{Deserialize, Serialize};");
p("");
p("use crate::call::{encode, query, Caller};");
p("use crate::error::SdkError;");
p("use crate::json::JsonValue;");
p("use crate::transport::Transport;");
p("");

// ---- schemas -----------------------------------------------------------------------------------
/** An `allOf` (a flattened struct on the server) becomes one object with all the fields. */
function flatten(s) {
  if (!s.allOf) return s;
  const out = { type: "object", properties: {}, required: [], description: s.description };
  for (const part of s.allOf) {
    const r = flatten(part.$ref ? schemas[refName(part.$ref)] : part);
    if (r.type !== "object") fail(`allOf part is ${r.type}`);
    Object.assign(out.properties, r.properties ?? {});
    out.required.push(...(r.required ?? []));
  }
  return out;
}

for (const name of Object.keys(schemas).sort()) {
  const s = flatten(schemas[name]);
  if (s.enum) {
    p(doc3(s.description, "").trimEnd());
    p("#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, uniffi::Enum)]");
    p(`pub enum ${name} {`);
    for (const v of s.enum) {
      p(`    #[serde(rename = "${v}")]`);
      p(`    ${pascal(v)},`);
    }
    p("}");
    p("");
    continue;
  }
  if (s.type !== "object") fail(`schema ${name} is ${s.type}`);
  const required = new Set(s.required ?? []);
  if (s.description) p(doc3(s.description, "").trimEnd());
  p("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, uniffi::Record)]");
  p(`pub struct ${name} {`);
  for (const [prop, ps] of Object.entries(s.properties ?? {})) {
    const r = rust(ps);
    const optional = r.opt || !required.has(prop);
    const text = ps.description ?? ps.oneOf?.find((x) => x.description)?.description;
    if (text) p(doc3(text, "    ").trimEnd());
    if (optional) p('    #[serde(default, skip_serializing_if = "Option::is_none")]');
    else if (r.t.startsWith("HashMap<") || r.t.startsWith("Vec<")) p("    #[serde(default)]");
    p(`    pub ${prop}: ${optional ? `Option<${r.t}>` : r.t},`);
  }
  p("}");
  p("");
}

// ---- operations --------------------------------------------------------------------------------
const methods = [];
for (const [path, item] of Object.entries(doc.paths)) {
  if (path === "/health") continue; // open, no token: ApiClient::health
  for (const [verb, op] of Object.entries(item)) {
    if (!["get", "post", "put", "delete"].includes(verb)) continue;
    const id = op.operationId ?? fail(`${verb} ${path} has no operationId`);
    const inPath = [...path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    // the document files every parameter of a `Query` struct under `path`; the URL says which are which
    const params = (op.parameters ?? []).map((x) => {
      const r = rust(x.schema);
      return { name: x.name, t: r.t, opt: r.opt || !(x.required && inPath.includes(x.name)), isPath: inPath.includes(x.name), description: x.description };
    });
    const pathParams = params.filter((x) => x.isPath);
    const queryParams = params.filter((x) => !x.isPath);

    let body = null;
    if (op.requestBody) {
      const c = op.requestBody.content;
      if (c["text/csv"]) body = { kind: "csv" };
      else if (c["application/json"]) {
        const r = rust(c["application/json"].schema);
        body = { kind: "json", t: r.t, opt: r.opt };
      } else fail(`body of ${id}: ${Object.keys(c)}`);
    }
    const okCode = Object.keys(op.responses).find((c) => c.startsWith("2")) ?? fail(`${id} has no success response`);
    const res = op.responses[okCode].content?.["application/json"];
    const ret = res ? rust(res.schema).t : null;

    const args = [
      ...pathParams.map((x) => `${x.name}: ${x.t}`),
      ...queryParams.map((x) => `${x.name}: Option<${x.t}>`),
      ...(body ? [body.kind === "csv" ? "csv: Vec<u8>" : `body: ${body.opt ? `Option<${body.t}>` : body.t}`] : []),
    ];
    let fmt = path.replace(/\{(\w+)\}/g, (_, n) => `{}`);
    const fmtArgs = pathParams.map((x) => `encode(&${x.name}.to_string())`);
    const qs = queryParams.length ? `${queryParams.map((x) => `("${x.name}", qv(&${x.name}))`).join(", ")}` : null;
    const urlExpr = (qs ? `format!("${fmt}{}", ${[...fmtArgs, `query(&[${qs}])`].join(", ")})` : fmtArgs.length ? `format!("${fmt}", ${fmtArgs.join(", ")})` : `"${fmt}".to_string()`)
      .replace(/"\$\{fmt\}/g, '"');
    const call =
      body?.kind === "csv"
        ? `self.caller.raw("${verb.toUpperCase()}", ${urlExpr}, "text/csv", csv)`
        : body
          ? `self.caller.json("${verb.toUpperCase()}", ${urlExpr}, ${body.opt ? "body.as_ref()" : "Some(&body)"})`
          : `self.caller.json("${verb.toUpperCase()}", ${urlExpr}, None::<&()>)`;
    methods.push({ id, doc: op.summary ?? op.description, args, ret, call, verb, path });
  }
}
methods.sort((a, b) => a.id.localeCompare(b.id));

p("/// The finance API of one server. Cheap to clone: it only holds the transport.");
p("#[derive(uniffi::Object)]");
p("pub struct FinanceSdk {");
p("    caller: Caller,");
p("}");
p("");
p("impl FinanceSdk {");
p("    /// A client that carries its requests with `transport`.");
p("    pub fn with_transport(transport: Arc<dyn Transport>) -> Arc<FinanceSdk> {");
p("        Arc::new(FinanceSdk { caller: Caller::new(transport) })");
p("    }");
p("}");
p("");
p("/// A query value as text: `None` is left out.");
p("fn qv<T: Serialize>(v: &Option<T>) -> Option<String> {");
p("    match serde_json::to_value(v.as_ref()?) {");
p("        Ok(serde_json::Value::String(s)) => Some(s),");
p("        Ok(other) => Some(other.to_string()),");
p("        Err(_) => None,");
p("    }");
p("}");
p("");
p('#[cfg_attr(not(target_arch = "wasm32"), uniffi::export(async_runtime = "tokio"))]');
p('#[cfg_attr(target_arch = "wasm32", uniffi::export)]');
p("impl FinanceSdk {");
p("    /// The finance API of the server at `base_url`, logged in with the server's token.");
p('    #[cfg(feature = "http")]');
p("    #[uniffi::constructor]");
p("    pub fn new(base_url: String, token: String) -> Arc<FinanceSdk> {");
p("        FinanceSdk::with_transport(Arc::new(crate::transport::HttpTransport::new(&base_url, &token)))");
p("    }");
for (const m of methods) {
  p("");
  p(`${doc3(m.doc ?? `${m.verb.toUpperCase()} ${m.path}`, "    ")}    pub async fn ${m.id}(&self${m.args.map((a) => `, ${a}`).join("")}) -> Result<${m.ret ?? "()"}, SdkError> {`.replace(/^\n/, ""));
  p(m.ret ? `        self.caller.decode(${m.call}.await?)` : `        ${m.call}.await.map(|_| ())`);
  p("    }");
}
p("}");
const text = lines.join("\n") + "\n";

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    // missing
  }
  if (current !== text) {
    console.error("crates/sdk/src/finance.rs is not what apps/mobile/openapi.json produces. Run: node crates/sdk/gen/finance.mjs");
    process.exit(1);
  }
  console.log(`finance.rs is current (${methods.length} calls, ${Object.keys(schemas).length} types)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote crates/sdk/src/finance.rs: ${methods.length} calls, ${Object.keys(schemas).length} types`);
}
